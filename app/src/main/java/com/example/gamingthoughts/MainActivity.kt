// FragmentActivity (not ComponentActivity) is required by BiometricPrompt.
class MainActivity : FragmentActivity() {
    private val vm: GameViewModel by viewModels()
    private var unlocked by mutableStateOf(false)

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent {
            GamingThoughtsTheme {
                if (unlocked) AppNav(vm) else LockScreen(onUnlock = ::authenticate)
            }
        }
        authenticate()
    }

    /** Technical feature 2: biometric unlock. Falls through if no biometrics are enrolled (e.g. emulator). */
    private fun authenticate() {
        val can = BiometricManager.from(this).canAuthenticate(
            BiometricManager.Authenticators.BIOMETRIC_WEAK or BiometricManager.Authenticators.DEVICE_CREDENTIAL
        )
        if (can != BiometricManager.BIOMETRIC_SUCCESS) { unlocked = true; return }
        val prompt = BiometricPrompt(this, ContextCompat.getMainExecutor(this),
            object : BiometricPrompt.AuthenticationCallback() {
                override fun onAuthenticationSucceeded(result: BiometricPrompt.AuthenticationResult) { unlocked = true }
            })
        prompt.authenticate(
            BiometricPrompt.PromptInfo.Builder()
                .setTitle(getString(R.string.unlock_title))
                .setAllowedAuthenticators(
                    BiometricManager.Authenticators.BIOMETRIC_WEAK or BiometricManager.Authenticators.DEVICE_CREDENTIAL
                )
                .build()
        )
    }
}

@Composable
private fun LockScreen(onUnlock: () -> Unit) {
    Column(Modifier.fillMaxSize().padding(24.dp), Arrangement.Center, Alignment.CenterHorizontally) {
        Text(stringResource(R.string.app_name), style = MaterialTheme.typography.headlineMedium)
        Spacer(Modifier.height(16.dp))
        Button(onClick = onUnlock) { Text(stringResource(R.string.unlock)) }
    }
}

@Composable
private fun AppNav(vm: GameViewModel) {
    val nav = rememberNavController()
    NavHost(nav, startDestination = "home") {
        composable("home") {
            HomeScreen(vm, onAdd = { nav.navigate("edit/-1") }, onOpen = { nav.navigate("detail/$it") })
        }
        composable("edit/{id}", listOf(navArgument("id") { type = NavType.IntType })) {
            AddEditScreen(vm, it.arguments!!.getInt("id"), onDone = { nav.popBackStack() })
        }
        composable("detail/{id}", listOf(navArgument("id") { type = NavType.IntType })) {
            val id = it.arguments!!.getInt("id")
            DetailScreen(vm, id, onBack = { nav.popBackStack() }, onEdit = { nav.navigate("edit/$id") })
        }
    }
}
